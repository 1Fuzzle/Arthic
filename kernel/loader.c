/* loader.c - turning a file into a running program.
 *
 * This is where everything so far comes together. Read bytes from ArthicFS,
 * ask the frame allocator for physical memory, use the MMU to make that memory
 * appear at the address the program was linked for, mark it user-accessible,
 * and drop to ring 3. Filesystem, allocator, paging, TSS, syscalls - all of it,
 * for one purpose.
 *
 * THE PROGRAM DESCRIBES ITSELF
 *
 * The file is ELF. Rather than the loader knowing where the program wants to
 * live and guessing at its structure, the program says so: an entry point, and
 * a table of segments each carrying an address, a size, and permissions.
 *
 * The loader's job becomes mechanical - walk the program headers, and for each
 * one that says PT_LOAD, put the requested bytes at the requested address with
 * the requested flags. No assumptions.
 *
 * WHAT THAT BUYS
 *
 * Code is mapped read-only and executable; writable data is mapped read-write.
 * The program cannot modify its own instructions, which with a flat image was
 * impossible to arrange because nothing distinguished the two.
 *
 * And memsz may exceed filesz. A segment can ask for more memory than it
 * occupies in the file, with the loader zeroing the difference - which is what
 * .bss is. A program wanting a megabyte of zeroed space needs no file to hold
 * the zeroes.
 *
 * VALIDATION
 *
 * Every field here came off a disk and is therefore untrusted, exactly like a
 * syscall argument. A malformed header could ask us to copy from beyond the end
 * of the file, or to map a page over kernel memory. Both are checked below.
 * Loaders that skip these checks are a well-trodden source of privilege
 * escalation.
 */

